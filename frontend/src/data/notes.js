function buildFallbackNote(selection) {
  const chapter = selection.chapter;
  const subject = selection.subject;
  const classLevel = selection.classLevel;

  const chapterHints = {
    Mathematics: [
      "core concepts",
      "problem-solving techniques",
      "logical reasoning",
      "step-by-step calculations"
    ],
    Science: [
      "scientific observations",
      "real-life phenomena",
      "experimental evidence",
      "cause and effect relations"
    ],
    English: [
      "language skills",
      "reading and writing practice",
      "literary understanding",
      "grammar and expression"
    ],
    "Social Science": [
      "historical events",
      "geographical context",
      "civic understanding",
      "social and economic patterns"
    ]
  };

  const selectedHints = chapterHints[subject] || chapterHints.Mathematics;

  return {
    classLevel,
    subject,
    chapter,
    title: chapter,
    introduction: `${chapter} is an important chapter in Class ${classLevel} ${subject}. It focuses on ${selectedHints[0]}, ${selectedHints[1]}, and the practical application of ideas in daily life. Students learn the key principles behind the chapter, connect them with real-world examples, and build the conceptual clarity needed for classroom understanding, board preparation, and revision. The chapter also encourages observation, interpretation, and step-by-step reasoning, which are essential in all subjects but especially valuable in ${subject}.`,
    importantConcepts: [
      `Main idea of ${chapter}`,
      `Key terms and definitions`,
      `Application in real life`,
      `Revision-based problem solving`
    ],
    keyPoints: [
      `The chapter explains the main principles behind ${chapter}.`,
      "Students must connect definitions, formulas, and facts with examples.",
      "Practice makes the explanation clearer and improves retention.",
      "Regular revision ensures confidence during tests and examinations."
    ],
    definitions: [
      { term: "Chapter focus", meaning: `This chapter develops understanding of the central idea behind ${chapter}.` },
      { term: "Concept connection", meaning: "Students should relate the topic to real examples, diagrams, and practical observations." },
      { term: "Revision", meaning: "Frequent review of concepts helps improve memory, accuracy, and speed in examinations." }
    ],
    quickRevision: [
      `Read the chapter summary and compare it with textbook examples.`,
      `Memorise key terms, definitions, and formulas wherever needed.`,
      `Practice one or two questions from each concept area.`,
      `Revisit the chapter after a short break to improve retention.`
    ]
  };
}

export const notes = defaultNotes;

export function findNote(selection) {
  const found = notes.find(
    (note) =>
      note.classLevel === selection.classLevel &&
      note.subject === selection.subject &&
      note.chapter === selection.chapter
  );

  return found || buildFallbackNote(selection);
}
